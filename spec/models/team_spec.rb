require 'rails_helper'

RSpec.describe Team, type: :model do
  subject(:team) { build(:team) }

  describe 'Associations' do
    it { is_expected.to belong_to(:account) }
    it { is_expected.to have_many(:team_users).dependent(:destroy) }
    it { is_expected.to have_many(:users).through(:team_users) }
    it { is_expected.to have_many(:inbox_teams).dependent(:destroy) }
    it { is_expected.to have_many(:inboxes).through(:inbox_teams) }
    it { is_expected.to have_many(:conversations).dependent(:nullify) }
    it { is_expected.to have_many(:macros).dependent(:nullify) }
  end

  describe 'Validations' do
    it { is_expected.to validate_presence_of(:name) }
    it { is_expected.to validate_length_of(:name).is_at_most(255) }

    # identifier is generated by SlugGenerator before validation if not present
    it 'validates uniqueness of identifier scoped to account_id' do
      create(:team)
      is_expected.to validate_uniqueness_of(:identifier).scoped_to(:account_id)
    end

    it 'validates that configurations is a hash' do
      team.configurations = 'not a hash'
      expect(team).not_to be_valid
      expect(team.errors[:configurations]).to include('must be a hash')
    end
  end

  describe 'Enums' do
    it { is_expected.to define_enum_for(:status).with_values(active: 0, inactive: 1, archived: 2) }
  end

  describe 'Scopes' do
    let!(:account) { create(:account) }
    let!(:team_with_member) { create(:team, account: account) }
    let!(:team_without_member) { create(:team, account: account) }
    let!(:user) { create(:user) }

    before do
      create(:account_user, account: account, user: user)
      create(:team_user, team: team_with_member, user: user)
    end

    describe '.with_members' do
      it 'returns only teams that have members' do
        expect(Team.with_members).to include(team_with_member)
        expect(Team.with_members).not_to include(team_without_member)
      end
    end

    describe '.by_account' do
      it 'returns teams for a specific account' do
        expect(Team.by_account(account)).to include(team_with_member, team_without_member)
      end
    end
  end

  describe 'Instance Methods' do
    let(:account) { create(:account) }
    let(:team) { create(:team, account: account) }
    let(:lead_user) { create(:user) }
    let(:member_user) { create(:user) }

    before do
      create(:account_user, account: account, user: lead_user)
      create(:account_user, account: account, user: member_user)
      create(:team_user, team: team, user: lead_user, role: :lead)
      create(:team_user, team: team, user: member_user, role: :member)
    end

    describe '#lead' do
      it 'returns the first lead user' do
        expect(team.lead).to eq(lead_user)
      end
    end

    describe '#leads' do
      it 'returns all lead users' do
        expect(team.leads.map(&:id)).to include(lead_user.id)
        expect(team.leads.map(&:id)).not_to include(member_user.id)
      end
    end

    describe '#members' do
      it 'returns all non-lead members' do
        expect(team.members.map(&:id)).to include(member_user.id)
        expect(team.members.map(&:id)).not_to include(lead_user.id)
      end
    end

    describe '#member?' do
      it 'returns true if user is a member' do
        expect(team.member?(member_user)).to be true
        expect(team.member?(lead_user)).to be true
      end

      it 'returns false if user is not a member' do
        other_user = create(:user)
        expect(team.member?(other_user)).to be false
      end
    end

    describe '#online_members' do
      it 'returns only online members' do
        AccountUser.find_by(account: account, user: lead_user).update!(availability: :online)
        AccountUser.find_by(account: account, user: member_user).update!(availability: :offline)

        expect(team.online_members).to include(lead_user)
        expect(team.online_members).not_to include(member_user)
      end
    end

    describe '#event_payload' do
      it 'returns a hash with team details' do
        payload = team.event_payload
        expect(payload[:name]).to eq(team.name)
        expect(payload[:member_count]).to eq(2)
      end
    end
  end

  describe 'Configurations' do
    it 'returns default round_robin policy' do
      team.configurations = {}
      expect(team.assignment_policy).to eq('round_robin')
    end

    it 'returns set assignment policy' do
      team.configurations = { 'assignment_policy' => 'load_balanced' }
      expect(team.assignment_policy).to eq('load_balanced')
    end

    it 'returns max_conversations_per_agent' do
      team.configurations = { 'max_conversations_per_agent' => 15 }
      expect(team.max_conversations_per_agent).to eq(15)
    end

    it 'returns auto_reassign_on_offline' do
      team.configurations = { 'auto_reassign_on_offline' => true }
      expect(team.auto_reassign_on_offline?).to be true
    end
  end
end
